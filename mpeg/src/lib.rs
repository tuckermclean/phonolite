//! An MPEG-1/2/2.5 audio decoder, Layers I, II and III: minimp3 ported to
//! safe Rust (CC0; see phonolite's `third_party/minimp3/`), without its
//! SIMD paths. Built for speed (opt-level 3) by the workspace, while the
//! player around it is built for size.
//!
//! Function names follow the C so the two can be read side by side.
//! Where the C relies on buffers having slack past their end, reads here
//! return zero; where a corrupt stream could walk the C past an array,
//! there is a guard. A damaged file decodes to noise or silence, never to
//! a panic. One addition: [`Decoder::eq`], a gain per channel and subband
//! applied before synthesis — mpg123's equalizer, done the same way.

#![forbid(unsafe_code)]
#![warn(missing_docs, rust_2018_idioms)]
// The port follows the C line by line so the two can be compared; index
// loops and the C's float literals stay as they are.
#![allow(clippy::needless_range_loop, clippy::excessive_precision)]

// Generated by tools/mpeg-tables.py: kept exactly as generated.
#[rustfmt::skip]
mod tables;

use tables::*;

const HDR_SIZE: usize = 4;
const MAX_FREE_FORMAT_FRAME_SIZE: usize = 2304;
const MAX_FRAME_SYNC_MATCHES: usize = 10;
const MAX_L3_FRAME_PAYLOAD_BYTES: usize = MAX_FREE_FORMAT_FRAME_SIZE;
const MAX_BITRESERVOIR_BYTES: usize = 511;
const SHORT_BLOCK_TYPE: u8 = 2;
const STOP_BLOCK_TYPE: u8 = 3;
const MODE_MONO: u8 = 3;
const MODE_JOINT_STEREO: u8 = 1;
const BITS_DEQUANTIZER_OUT: i32 = -1;
const MAX_SCF: i32 = 255 + BITS_DEQUANTIZER_OUT * 4 - 210;
const MAX_SCFI: i32 = (MAX_SCF + 3) & !3;

/// Interleaved samples one frame can produce at most (1152 × 2 channels).
pub const MAX_SAMPLES_PER_FRAME: usize = 1152 * 2;

// ------------------------------------------------------------------ header

fn hdr_is_mono(h: &[u8]) -> bool {
    h[3] & 0xC0 == 0xC0
}
fn hdr_is_ms_stereo(h: &[u8]) -> bool {
    h[3] & 0xE0 == 0x60
}
fn hdr_is_free_format(h: &[u8]) -> bool {
    h[2] & 0xF0 == 0
}
fn hdr_is_crc(h: &[u8]) -> bool {
    h[1] & 1 == 0
}
fn hdr_test_padding(h: &[u8]) -> bool {
    h[2] & 0x2 != 0
}
fn hdr_test_mpeg1(h: &[u8]) -> bool {
    h[1] & 0x8 != 0
}
fn hdr_test_not_mpeg25(h: &[u8]) -> bool {
    h[1] & 0x10 != 0
}
fn hdr_test_i_stereo(h: &[u8]) -> bool {
    h[3] & 0x10 != 0
}
fn hdr_test_ms_stereo(h: &[u8]) -> bool {
    h[3] & 0x20 != 0
}
fn hdr_get_stereo_mode(h: &[u8]) -> u8 {
    (h[3] >> 6) & 3
}
fn hdr_get_stereo_mode_ext(h: &[u8]) -> u8 {
    (h[3] >> 4) & 3
}
fn hdr_get_layer(h: &[u8]) -> u8 {
    (h[1] >> 1) & 3
}
fn hdr_get_bitrate(h: &[u8]) -> u8 {
    h[2] >> 4
}
fn hdr_get_sample_rate(h: &[u8]) -> u8 {
    (h[2] >> 2) & 3
}
fn hdr_get_my_sample_rate(h: &[u8]) -> usize {
    usize::from(hdr_get_sample_rate(h)) + usize::from(((h[1] >> 3) & 1) + ((h[1] >> 4) & 1)) * 3
}
fn hdr_is_frame_576(h: &[u8]) -> bool {
    h[1] & 14 == 2
}
fn hdr_is_layer_1(h: &[u8]) -> bool {
    h[1] & 6 == 6
}

fn hdr_valid(h: &[u8]) -> bool {
    h.len() >= HDR_SIZE
        && h[0] == 0xff
        && ((h[1] & 0xF0) == 0xf0 || (h[1] & 0xFE) == 0xe2)
        && hdr_get_layer(h) != 0
        && hdr_get_bitrate(h) != 15
        && hdr_get_sample_rate(h) != 3
}

fn hdr_compare(h1: &[u8], h2: &[u8]) -> bool {
    hdr_valid(h2) && (h1[1] ^ h2[1]) & 0xFE == 0 && (h1[2] ^ h2[2]) & 0x0C == 0 && hdr_is_free_format(h1) == hdr_is_free_format(h2)
}

fn hdr_bitrate_kbps(h: &[u8]) -> u32 {
    2 * u32::from(HALFRATE[usize::from(hdr_test_mpeg1(h))][usize::from(hdr_get_layer(h)) - 1][usize::from(hdr_get_bitrate(h))])
}

fn hdr_sample_rate_hz(h: &[u8]) -> u32 {
    const HZ: [u32; 3] = [44100, 48000, 32000];
    HZ[usize::from(hdr_get_sample_rate(h))] >> u32::from(!hdr_test_mpeg1(h)) >> u32::from(!hdr_test_not_mpeg25(h))
}

fn hdr_frame_samples(h: &[u8]) -> usize {
    if hdr_is_layer_1(h) {
        384
    } else {
        1152 >> usize::from(hdr_is_frame_576(h))
    }
}

fn hdr_frame_bytes(h: &[u8], free_format_size: usize) -> usize {
    let mut frame_bytes = hdr_frame_samples(h) * hdr_bitrate_kbps(h) as usize * 125 / hdr_sample_rate_hz(h) as usize;
    if hdr_is_layer_1(h) {
        frame_bytes &= !3; // slot align
    }
    if frame_bytes != 0 {
        frame_bytes
    } else {
        free_format_size
    }
}

fn hdr_padding(h: &[u8]) -> usize {
    if hdr_test_padding(h) {
        if hdr_is_layer_1(h) {
            4
        } else {
            1
        }
    } else {
        0
    }
}

// --------------------------------------------------------------- bitstream

struct Bs<'a> {
    buf: &'a [u8],
    pos: usize,
    limit: usize,
}

impl Bs<'_> {
    fn get_bits(&mut self, n: u32) -> u32 {
        let s = (self.pos & 7) as i32;
        let mut shl = n as i32 + s;
        let mut p = self.pos >> 3;
        self.pos += n as usize;
        if self.pos > self.limit {
            return 0;
        }
        let byte = |i: usize| u32::from(self.buf.get(i).copied().unwrap_or(0));
        let mut next = byte(p) & (255 >> s);
        p += 1;
        let mut cache = 0u32;
        loop {
            shl -= 8;
            if shl <= 0 {
                break;
            }
            cache |= next << shl;
            next = byte(p);
            p += 1;
        }
        cache | (next >> -shl)
    }
}

// ------------------------------------------------------------- layers I, II

struct L12ScaleInfo {
    scf: [f32; 3 * 64],
    total_bands: usize,
    stereo_bands: usize,
    bitalloc: [u8; 64],
    scfcod: [u8; 64],
}

#[derive(Clone, Copy)]
struct SubbandAlloc {
    tab_offset: u8,
    code_tab_width: u8,
    band_count: u8,
}

const fn sa(tab_offset: u8, code_tab_width: u8, band_count: u8) -> SubbandAlloc {
    SubbandAlloc { tab_offset, code_tab_width, band_count }
}

fn l12_subband_alloc_table(hdr: &[u8], sci: &mut L12ScaleInfo) -> &'static [SubbandAlloc] {
    static ALLOC_L1: [SubbandAlloc; 1] = [sa(76, 4, 32)];
    static ALLOC_L2M2: [SubbandAlloc; 3] = [sa(60, 4, 4), sa(44, 3, 7), sa(44, 2, 19)];
    static ALLOC_L2M1: [SubbandAlloc; 4] = [sa(0, 4, 3), sa(16, 4, 8), sa(32, 3, 12), sa(40, 2, 7)];
    static ALLOC_L2M1_LOWRATE: [SubbandAlloc; 2] = [sa(44, 4, 2), sa(44, 3, 10)];
    let mode = hdr_get_stereo_mode(hdr);
    let stereo_bands = if mode == MODE_MONO {
        0
    } else if mode == MODE_JOINT_STEREO {
        (usize::from(hdr_get_stereo_mode_ext(hdr)) << 2) + 4
    } else {
        32
    };
    let (alloc, nbands): (&'static [SubbandAlloc], usize) = if hdr_is_layer_1(hdr) {
        (&ALLOC_L1, 32)
    } else if !hdr_test_mpeg1(hdr) {
        (&ALLOC_L2M2, 30)
    } else {
        let sample_rate_idx = hdr_get_sample_rate(hdr);
        let mut kbps = hdr_bitrate_kbps(hdr) >> u32::from(mode != MODE_MONO);
        if kbps == 0 {
            kbps = 192; // free format
        }
        if kbps < 56 {
            (&ALLOC_L2M1_LOWRATE, if sample_rate_idx == 2 { 12 } else { 8 })
        } else if kbps >= 96 && sample_rate_idx != 1 {
            (&ALLOC_L2M1, 30)
        } else {
            (&ALLOC_L2M1, 27)
        }
    };
    sci.total_bands = nbands;
    sci.stereo_bands = stereo_bands.min(nbands);
    alloc
}

fn l12_read_scalefactors(bs: &mut Bs<'_>, sci: &mut L12ScaleInfo, bands: usize) {
    let mut k = 0;
    for i in 0..bands {
        let mut s = 0.0;
        let ba = usize::from(sci.bitalloc[i]);
        let mask = if ba != 0 { 4 + ((19 >> sci.scfcod[i]) & 3) } else { 0 };
        let mut m = 4;
        while m != 0 {
            if mask & m != 0 {
                let b = bs.get_bits(6) as usize;
                let idx = (ba * 3 + b % 3).wrapping_sub(6);
                s = DEQ_L12.get(idx).copied().unwrap_or(0.0) * ((1i32 << 21) >> (b / 3)) as f32;
            }
            sci.scf[k] = s;
            k += 1;
            m >>= 1;
        }
    }
}

fn l12_read_scale_info(hdr: &[u8], bs: &mut Bs<'_>, sci: &mut L12ScaleInfo) {
    let alloc = l12_subband_alloc_table(hdr, sci);
    let (mut k, mut ba_bits, mut tab_off, mut ai) = (0, 0u32, 0usize, 0);
    for i in 0..sci.total_bands {
        if i == k {
            let a = alloc[ai.min(alloc.len() - 1)];
            k += usize::from(a.band_count);
            ba_bits = u32::from(a.code_tab_width);
            tab_off = usize::from(a.tab_offset);
            ai += 1;
        }
        let code = |bs: &mut Bs<'_>| BITALLOC_CODE_TAB.get(tab_off + bs.get_bits(ba_bits) as usize).copied().unwrap_or(0);
        let mut ba = code(bs);
        sci.bitalloc[2 * i] = ba;
        if i < sci.stereo_bands {
            ba = code(bs);
        }
        sci.bitalloc[2 * i + 1] = if sci.stereo_bands != 0 { ba } else { 0 };
    }
    for i in 0..2 * sci.total_bands {
        sci.scfcod[i] = if sci.bitalloc[i] != 0 {
            if hdr_is_layer_1(hdr) {
                2
            } else {
                bs.get_bits(2) as u8
            }
        } else {
            6
        };
    }
    l12_read_scalefactors(bs, sci, sci.total_bands * 2);
    for i in sci.stereo_bands..sci.total_bands {
        sci.bitalloc[2 * i + 1] = 0;
    }
}

fn l12_dequantize_granule(grbuf: &mut [f32], start: usize, bs: &mut Bs<'_>, sci: &L12ScaleInfo, group_size: usize) -> usize {
    let mut choff: isize = 576;
    for j in 0..4 {
        let mut dst = (start + group_size * j) as isize;
        for i in 0..2 * sci.total_bands {
            let ba = u32::from(sci.bitalloc[i]);
            if ba != 0 {
                if ba < 17 {
                    let half = (1i32 << (ba - 1)) - 1;
                    for k in 0..group_size {
                        let v = bs.get_bits(ba) as i32 - half;
                        if let Some(d) = grbuf.get_mut(dst as usize + k) {
                            *d = v as f32;
                        }
                    }
                } else {
                    let m = (2u32 << (ba - 17)) + 1; // 3, 5, 9
                    let mut code = bs.get_bits(m + 2 - (m >> 3)); // 5, 7, 10 bits
                    for k in 0..group_size {
                        if let Some(d) = grbuf.get_mut(dst as usize + k) {
                            *d = (code % m) as f32 - (m / 2) as f32;
                        }
                        code /= m;
                    }
                }
            }
            dst += choff;
            choff = 18 - choff;
        }
    }
    group_size * 4
}

fn l12_apply_scf_384(sci: &L12ScaleInfo, scf_base: usize, dst: &mut [f32]) {
    let (sb, tb) = (sci.stereo_bands, sci.total_bands);
    dst.copy_within(sb * 18..tb * 18, 576 + sb * 18);
    for i in 0..tb {
        let (l, r) = (sci.scf[scf_base + 6 * i], sci.scf[scf_base + 6 * i + 3]);
        for k in 0..12 {
            dst[18 * i + k] *= l;
            dst[18 * i + k + 576] *= r;
        }
    }
}

