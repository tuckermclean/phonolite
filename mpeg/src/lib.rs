#[derive(Clone, Copy)]
struct GrInfo {
    sfbtab: &'static [u8],
    part_23_length: u16,
    big_values: u16,
    scalefac_compress: u16,
    global_gain: u8,
    block_type: u8,
    mixed_block_flag: u8,
    n_long_sfb: u8,
    n_short_sfb: u8,
    table_select: [u8; 3],
    region_count: [u8; 3],
    subblock_gain: [u8; 3],
    preflag: u8,
    scalefac_scale: u8,
    count1_table: u8,
    scfsi: u8,
}

const GR_EMPTY: GrInfo = GrInfo {
    sfbtab: &[0],
    part_23_length: 0,
    big_values: 0,
    scalefac_compress: 0,
    global_gain: 0,
    block_type: 0,
    mixed_block_flag: 0,
    n_long_sfb: 0,
    n_short_sfb: 0,
    table_select: [0; 3],
    region_count: [0; 3],
    subblock_gain: [0; 3],
    preflag: 0,
    scalefac_scale: 0,
    count1_table: 0,
    scfsi: 0,
};

fn l3_read_side_info(bs: &mut Bs<'_>, gr: &mut [GrInfo; 4], hdr: &[u8]) -> i32 {
    let mut scfsi: u32 = 0;
    let mut part_23_sum = 0usize;
    let mut gr_count = if hdr_is_mono(hdr) { 1 } else { 2 };
    let mut sr_idx = hdr_get_my_sample_rate(hdr);
    sr_idx -= usize::from(sr_idx != 0);
    let main_data_begin;
    if hdr_test_mpeg1(hdr) {
        gr_count *= 2;
        main_data_begin = bs.get_bits(9) as i32;
        scfsi = bs.get_bits(7 + gr_count);
    } else {
        main_data_begin = (bs.get_bits(8 + gr_count) >> gr_count) as i32;
    }
    let sr_idx = sr_idx.min(7);
    for g in gr.iter_mut().take(gr_count as usize) {
        if hdr_is_mono(hdr) {
            scfsi <<= 4;
        }
        g.part_23_length = bs.get_bits(12) as u16;
        part_23_sum += usize::from(g.part_23_length);
        g.big_values = bs.get_bits(9) as u16;
        if g.big_values > 288 {
            return -1;
        }
        g.global_gain = bs.get_bits(8) as u8;
        g.scalefac_compress = bs.get_bits(if hdr_test_mpeg1(hdr) { 4 } else { 9 }) as u16;
        g.sfbtab = &SCF_LONG[sr_idx];
        g.n_long_sfb = 22;
        g.n_short_sfb = 0;
        let tables;
        if bs.get_bits(1) != 0 {
            g.block_type = bs.get_bits(2) as u8;
            if g.block_type == 0 {
                return -1;
            }
            g.mixed_block_flag = bs.get_bits(1) as u8;
            g.region_count[0] = 7;
            g.region_count[1] = 255;
            if g.block_type == SHORT_BLOCK_TYPE {
                scfsi &= 0x0F0F;
                if g.mixed_block_flag == 0 {
                    g.region_count[0] = 8;
                    g.sfbtab = &SCF_SHORT[sr_idx];
                    g.n_long_sfb = 0;
                    g.n_short_sfb = 39;
                } else {
                    g.sfbtab = &SCF_MIXED[sr_idx];
                    g.n_long_sfb = if hdr_test_mpeg1(hdr) { 8 } else { 6 };
                    g.n_short_sfb = 30;
                }
            }
            tables = bs.get_bits(10) << 5;
            for s in &mut g.subblock_gain {
                *s = bs.get_bits(3) as u8;
            }
        } else {
            g.block_type = 0;
            g.mixed_block_flag = 0;
            tables = bs.get_bits(15);
            g.region_count[0] = bs.get_bits(4) as u8;
            g.region_count[1] = bs.get_bits(3) as u8;
            g.region_count[2] = 255;
        }
        g.table_select = [(tables >> 10) as u8, ((tables >> 5) & 31) as u8, (tables & 31) as u8];
        g.preflag = if hdr_test_mpeg1(hdr) { bs.get_bits(1) as u8 } else { u8::from(g.scalefac_compress >= 500) };
        g.scalefac_scale = bs.get_bits(1) as u8;
        g.count1_table = bs.get_bits(1) as u8;
        g.scfsi = ((scfsi >> 12) & 15) as u8;
        scfsi <<= 4;
    }
    if part_23_sum + bs.pos > bs.limit + main_data_begin as usize * 8 {
        return -1;
    }
    main_data_begin
}

fn l3_read_scalefactors(scf: &mut [u8; 40], ist_pos: &mut [u8; 39], scf_size: &[u8; 4], scf_count: &[u8], bs: &mut Bs<'_>, mut scfsi: i32) {
    let mut at = 0usize;
    for i in 0..4 {
        let cnt = usize::from(scf_count.get(i).copied().unwrap_or(0));
        if cnt == 0 {
            break;
        }
        let cnt = cnt.min(39usize.saturating_sub(at));
        if scfsi & 8 != 0 {
            scf[at..at + cnt].copy_from_slice(&ist_pos[at..at + cnt]);
        } else {
            let bits = u32::from(scf_size[i]);
            if bits == 0 {
                scf[at..at + cnt].fill(0);
                ist_pos[at..at + cnt].fill(0);
            } else {
                let max_scf: i32 = if scfsi < 0 { (1 << bits) - 1 } else { -1 };
                for k in 0..cnt {
                    let s = bs.get_bits(bits) as i32;
                    ist_pos[at + k] = if s == max_scf { 255 } else { s as u8 };
                    scf[at + k] = s as u8;
                }
            }
        }
        at += cnt;
        scfsi = scfsi.wrapping_mul(2);
    }
    for z in scf.iter_mut().skip(at).take(3) {
        *z = 0;
    }
}

fn l3_ldexp_q2(mut y: f32, mut exp_q2: i32) -> f32 {
    loop {
        let e = (30 * 4).min(exp_q2).max(0);
        y *= EXPFRAC[(e & 3) as usize] * ((1i32 << 30) >> (e >> 2)) as f32;
        exp_q2 -= e;
        if exp_q2 <= 0 || e == 0 {
            return y;
        }
    }
}

fn l3_decode_scalefactors(hdr: &[u8], ist_pos: &mut [u8; 39], bs: &mut Bs<'_>, gr: &GrInfo, scf: &mut [f32; 40], ch: usize) {
    let part = usize::from(gr.n_short_sfb != 0) + usize::from(gr.n_long_sfb == 0);
    let mut partition_off = 0;
    let mut scf_size = [0u8; 4];
    let mut iscf = [0u8; 40];
    let scf_shift = u32::from(gr.scalefac_scale) + 1;
    let mut scfsi = i32::from(gr.scfsi);
    if hdr_test_mpeg1(hdr) {
        let p = SCFC_DECODE[usize::from(gr.scalefac_compress & 15)];
        scf_size = [p >> 2, p >> 2, p & 3, p & 3];
    } else {
        let ist = usize::from(hdr_test_i_stereo(hdr) && ch != 0);
        let mut sfc = i32::from(gr.scalefac_compress >> ist);
        let mut k = ist * 3 * 4;
        while sfc >= 0 && k + 4 <= MOD.len() {
            let mut modprod = 1i32;
            for i in (0..4).rev() {
                let m = i32::from(MOD[k + i]);
                scf_size[i] = (sfc / modprod % m) as u8;
                modprod *= m;
            }
            sfc -= modprod;
            k += 4;
        }
        partition_off = k;
        scfsi = -16;
    }
    let partition = &SCF_PARTITIONS[part][partition_off.min(28)..];
    l3_read_scalefactors(&mut iscf, ist_pos, &scf_size, partition, bs, scfsi);

    let (nl, ns) = (usize::from(gr.n_long_sfb), usize::from(gr.n_short_sfb));
    if ns != 0 {
        let sh = 3 - scf_shift;
        let mut i = 0;
        while i < ns && nl + i + 2 < 40 {
            for (j, g) in gr.subblock_gain.iter().enumerate() {
                iscf[nl + i + j] = iscf[nl + i + j].wrapping_add(g << sh);
            }
            i += 3;
        }
    } else if gr.preflag != 0 {
        for (i, p) in PREAMP.iter().enumerate() {
            iscf[11 + i] = iscf[11 + i].wrapping_add(*p);
        }
    }
    let gain_exp = i32::from(gr.global_gain) + BITS_DEQUANTIZER_OUT * 4 - 210 - if hdr_is_ms_stereo(hdr) { 2 } else { 0 };
    let gain = l3_ldexp_q2((1i32 << (MAX_SCFI / 4)) as f32, MAX_SCFI - gain_exp);
    for i in 0..(nl + ns).min(40) {
        scf[i] = l3_ldexp_q2(gain, i32::from(iscf[i]) << scf_shift);
    }
}

fn l3_pow_43(mut x: i32) -> f32 {
    if x < 129 {
        return POW43[(16 + x).max(0) as usize];
    }
    let mut mult = 256.0;
    if x < 1024 {
        mult = 16.0;
        x <<= 3;
    }
    let sign = (2 * x) & 64;
    let frac = ((x & 63) - sign) as f32 / ((x & !63) + sign) as f32;
    POW43.get((16 + ((x + sign) >> 6)) as usize).copied().unwrap_or(0.0) * (1.0 + frac * ((4.0 / 3.0) + frac * (2.0 / 9.0))) * mult
}

/// The Huffman-coded spectrum of one granule and channel.
fn l3_huffman(dst: &mut [f32], bs: &mut Bs<'_>, gr: &GrInfo, scf: &[f32; 40], layer3gr_limit: usize) {
    let buf = bs.buf;
    let byte = |i: usize| u32::from(buf.get(i).copied().unwrap_or(0));
    let mut next = bs.pos / 8;
    let mut cache: u32 = ((((byte(next) << 8 | byte(next + 1)) << 8 | byte(next + 2)) << 8) | byte(next + 3)) << (bs.pos & 7);
    let mut sh: i32 = (bs.pos & 7) as i32 - 8;
    next += 4;
    macro_rules! peek {
        ($n:expr) => {{
            let n: u32 = $n as u32;
            if n == 0 {
                0
            } else {
                cache >> (32 - n)
            }
        }};
    }
    macro_rules! flush {
        ($n:expr) => {{
            let n: u32 = $n as u32;
            cache = if n >= 32 { 0 } else { cache << n };
            sh += n as i32;
        }};
    }
    macro_rules! check {
        () => {
            while sh >= 0 {
                cache |= byte(next) << sh;
                next += 1;
                sh -= 8;
            }
        };
    }
    let bspos = |next: usize, sh: i32| (next as i64) * 8 - 24 + i64::from(sh);

    let sfb = gr.sfbtab;
    let mut si = 0usize; // into sfb
    let mut sc = 0usize; // into scf
    let mut d = 0usize; // into dst
    let mut one = 0.0f32;
    let mut ireg = 0;
    let mut big_val_cnt = i32::from(gr.big_values);
    'big: while big_val_cnt > 0 && ireg < 3 {
        let tab_num = usize::from(gr.table_select[ireg]);
        let mut sfb_cnt = i32::from(gr.region_count[ireg]);
        ireg += 1;
        let cb = TABINDEX[tab_num & 31] as isize;
        let linbits = u32::from(LINBITS[tab_num & 31]);
        loop {
            let np = i32::from(sfb.get(si).copied().unwrap_or(0)) / 2;
            si += 1;
            if np == 0 {
                break 'big; // the band table ran out: corrupt
            }
            let mut pairs = big_val_cnt.min(np);
            one = scf[sc.min(39)];
            sc += 1;
            loop {
                if d + 2 > dst.len() {
                    break 'big;
                }
                let mut w: u32 = 5;
                let mut leaf = i32::from(HUFF_TABS.get((cb + peek!(w) as isize) as usize).copied().unwrap_or(0));
                while leaf < 0 {
                    flush!(w);
                    w = (leaf & 7) as u32;
                    let idx = cb + peek!(w) as isize - (leaf >> 3) as isize;
                    leaf = i32::from(HUFF_TABS.get(idx as usize).copied().unwrap_or(0));
                }
                flush!(leaf >> 8);
                for _ in 0..2 {
                    let mut lsb = leaf & 0x0F;
                    if linbits != 0 && lsb == 15 {
                        lsb += peek!(linbits) as i32;
                        flush!(linbits);
                        check!();
                        dst[d] = one * l3_pow_43(lsb) * if (cache as i32) < 0 { -1.0 } else { 1.0 };
                    } else {
                        dst[d] = POW43[(16 + lsb - 16 * (cache >> 31) as i32) as usize] * one;
                    }
                    flush!(u32::from(lsb != 0));
                    d += 1;
                    leaf >>= 4;
                }
                check!();
                pairs -= 1;
                if pairs <= 0 {
                    break;
                }
            }
            big_val_cnt -= np;
            if big_val_cnt <= 0 {
                break;
            }
            sfb_cnt -= 1;
            if sfb_cnt < 0 {
                break;
            }
        }
    }

    let mut np = 1 - big_val_cnt;
    loop {
        let cb1: &[u8] = if gr.count1_table != 0 { &TAB33 } else { &TAB32 };
        let mut leaf = i32::from(cb1[peek!(4) as usize]);
        if leaf & 8 == 0 {
            let n = (leaf & 3) as u32;
            let idx = (leaf >> 3) as usize + if n == 0 { 0 } else { ((cache << 4) >> (32 - n)) as usize };
            leaf = i32::from(cb1.get(idx).copied().unwrap_or(0));
        }
        flush!(leaf & 7);
        if bspos(next, sh) > layer3gr_limit as i64 || d + 4 > dst.len() {
            break;
        }
        macro_rules! reload {
            () => {
                np -= 1;
                if np == 0 {
                    np = i32::from(sfb.get(si).copied().unwrap_or(0)) / 2;
                    si += 1;
                    if np == 0 {
                        break;
                    }
                    one = scf[sc.min(39)];
                    sc += 1;
                }
            };
        }
        macro_rules! deq {
            ($s:expr) => {
                if leaf & (128 >> $s) != 0 {
                    dst[d + $s] = if (cache as i32) < 0 { -one } else { one };
                    flush!(1);
                }
            };
        }
        reload!();
        deq!(0);
        deq!(1);
        reload!();
        deq!(2);
        deq!(3);
        check!();
        d += 4;
    }
    bs.pos = layer3gr_limit;
}

fn l3_midside_stereo(g: &mut [f32], left: usize, n: usize) {
    for i in left..(left + n).min(576) {
        let (a, b) = (g[i], g[i + 576]);
        g[i] = a + b;
        g[i + 576] = a - b;
    }
}

fn l3_intensity_stereo_band(g: &mut [f32], left: usize, n: usize, kl: f32, kr: f32) {
    for i in left..(left + n).min(576) {
        g[i + 576] = g[i] * kr;
        g[i] *= kl;
    }
}

fn l3_stereo_top_band(g: &[f32], sfb: &[u8], nbands: usize, max_band: &mut [i32; 3]) {
    *max_band = [-1; 3];
    let mut right = 576;
    for i in 0..nbands.min(sfb.len()) {
        let n = usize::from(sfb[i]);
        let mut k = 0;
        while k < n && right + k + 1 < 1152 {
            if g[right + k] != 0.0 || g[right + k + 1] != 0.0 {
                max_band[i % 3] = i as i32;
                break;
            }
            k += 2;
        }
        right += n;
    }
}

fn l3_stereo_process(g: &mut [f32], ist_pos: &[u8; 39], sfb: &[u8], hdr: &[u8], max_band: &[i32; 3], mpeg2_sh: u32) {
    let mpeg1 = hdr_test_mpeg1(hdr);
    let max_pos = if mpeg1 { 7 } else { 64 };
    let mut left = 0;
    let mut i = 0;
    while i < sfb.len() && sfb[i] != 0 && i < 39 {
        let n = usize::from(sfb[i]);
        let ipos = u32::from(ist_pos[i]);
        if i as i32 > max_band[i % 3] && ipos < max_pos {
            let s = if hdr_test_ms_stereo(hdr) { std::f32::consts::SQRT_2 } else { 1.0 };
            let (mut kl, mut kr);
            if mpeg1 {
                kl = PAN[2 * ipos as usize];
                kr = PAN[2 * ipos as usize + 1];
            } else {
                kl = 1.0;
                kr = l3_ldexp_q2(1.0, (((ipos + 1) >> 1) << mpeg2_sh) as i32);
                if ipos & 1 != 0 {
                    kl = kr;
                    kr = 1.0;
                }
            }
            l3_intensity_stereo_band(g, left, n, kl * s, kr * s);
        } else if hdr_test_ms_stereo(hdr) {
            l3_midside_stereo(g, left, n);
        }
        left += n;
        i += 1;
    }
}

fn l3_intensity_stereo(g: &mut [f32], ist_pos: &mut [u8; 39], gr: &[GrInfo], hdr: &[u8]) {
    let mut max_band = [0i32; 3];
    let n_sfb = usize::from(gr[0].n_long_sfb) + usize::from(gr[0].n_short_sfb);
    let max_blocks = if gr[0].n_short_sfb != 0 { 3 } else { 1 };
    l3_stereo_top_band(g, gr[0].sfbtab, n_sfb, &mut max_band);
    if gr[0].n_long_sfb != 0 {
        let m = max_band[0].max(max_band[1]).max(max_band[2]);
        max_band = [m; 3];
    }
    for i in 0..max_blocks {
        let default_pos = if hdr_test_mpeg1(hdr) { 3 } else { 0 };
        let itop = n_sfb - max_blocks + i;
        let prev = itop - max_blocks;
        if itop < 39 {
            ist_pos[itop] = if max_band[i] >= prev as i32 { default_pos } else { ist_pos[prev] };
        }
    }
    l3_stereo_process(g, ist_pos, gr[0].sfbtab, hdr, &max_band, u32::from(gr[1].scalefac_compress & 1));
}

fn l3_reorder(g: &mut [f32], start: usize, scratch: &mut [f32], sfb: &[u8]) {
    let (mut src, mut dst, mut k) = (start, 0, 0);
    while k < sfb.len() && sfb[k] != 0 {
        let len = usize::from(sfb[k]);
        if src + 3 * len > g.len() || dst + 3 * len > scratch.len() {
            break;
        }
        for i in 0..len {
            scratch[dst] = g[src + i];
            scratch[dst + 1] = g[src + i + len];
            scratch[dst + 2] = g[src + i + 2 * len];
            dst += 3;
        }
        src += 3 * len;
        k += 3;
    }
    g[start..start + dst].copy_from_slice(&scratch[..dst]);
}

fn l3_antialias(g: &mut [f32], base: usize, nbands: i32) {
    for b in 0..nbands.max(0) as usize {
        let off = base + 18 * b;
        for i in 0..8 {
            let u = g[off + 18 + i];
            let d = g[off + 17 - i];
            g[off + 18 + i] = u * AA[0][i] - d * AA[1][i];
            g[off + 17 - i] = u * AA[1][i] + d * AA[0][i];
        }
    }
}

fn l3_dct3_9(y: &mut [f32; 9]) {
    let (mut s0, mut s2, mut s4, mut s6, mut s8) = (y[0], y[2], y[4], y[6], y[8]);
    let mut t0 = s0 + s6 * 0.5;
    s0 -= s6;
    let mut t4 = (s4 + s2) * 0.93969262;
    let mut t2 = (s8 + s2) * 0.76604444;
    s6 = (s4 - s8) * 0.17364818;
    s4 += s8 - s2;

    s2 = s0 - s4 * 0.5;
    y[4] = s4 + s0;
    s8 = t0 - t2 + s6;
    s0 = t0 - t4 + t2;
    s4 = t0 + t4 - s6;

    let (mut s1, mut s3, mut s5, mut s7) = (y[1], y[3], y[5], y[7]);
    s3 *= 0.86602540;
    t0 = (s5 + s1) * 0.98480775;
    t4 = (s5 - s7) * 0.34202014;
    t2 = (s1 + s7) * 0.64278761;
    s1 = (s1 - s5 - s7) * 0.86602540;

    s5 = t0 - s3 - t2;
    s7 = t4 - s3 - t0;
    s3 = t4 + s3 - t2;

    y[0] = s4 - s7;
    y[1] = s2 + s1;
    y[2] = s0 - s3;
    y[3] = s8 + s5;
    y[5] = s8 - s5;
    y[6] = s0 + s3;
    y[7] = s2 - s1;
    y[8] = s4 + s7;
}

fn l3_imdct36(g: &mut [f32], gbase: usize, overlap: &mut [f32], obase: usize, window: &[f32; 18], nbands: usize) {
    for j in 0..nbands {
        let (go, oo) = (gbase + 18 * j, obase + 9 * j);
        let x = &mut g[go..go + 18];
        let mut co = [0.0f32; 9];
        let mut si = [0.0f32; 9];
        co[0] = -x[0];
        si[0] = x[17];
        for i in 0..4 {
            si[8 - 2 * i] = x[4 * i + 1] - x[4 * i + 2];
            co[1 + 2 * i] = x[4 * i + 1] + x[4 * i + 2];
            si[7 - 2 * i] = x[4 * i + 4] - x[4 * i + 3];
            co[2 + 2 * i] = -(x[4 * i + 3] + x[4 * i + 4]);
        }
        l3_dct3_9(&mut co);
        l3_dct3_9(&mut si);
        si[1] = -si[1];
        si[3] = -si[3];
        si[5] = -si[5];
        si[7] = -si[7];
        let ov = &mut overlap[oo..oo + 9];
        for i in 0..9 {
            let ovl = ov[i];
            let sum = co[i] * TWID9[9 + i] + si[i] * TWID9[i];
            ov[i] = co[i] * TWID9[i] - si[i] * TWID9[9 + i];
            x[i] = ovl * window[i] - sum * window[9 + i];
            x[17 - i] = ovl * window[9 + i] + sum * window[i];
        }
    }
}

fn l3_idct3(x0: f32, x1: f32, x2: f32) -> [f32; 3] {
    let m1 = x1 * 0.86602540;
    let a1 = x0 - x2 * 0.5;
    [a1 + m1, x0 + x2, a1 - m1]
}

/// `x` is read at a stride of 3; writes `dst[..6]`, updates `overlap[..3]`.
fn l3_imdct12(x: &[f32], dst: &mut [f32], overlap: &mut [f32]) {
    let co = l3_idct3(-x[0], x[6] + x[3], x[12] + x[9]);
    let mut si = l3_idct3(x[15], x[12] - x[9], x[6] - x[3]);
    si[1] = -si[1];
    for i in 0..3 {
        let ovl = overlap[i];
        let sum = co[i] * TWID3[3 + i] + si[i] * TWID3[i];
        overlap[i] = co[i] * TWID3[i] - si[i] * TWID3[3 + i];
        dst[i] = ovl * TWID3[2 - i] - sum * TWID3[5 - i];
        dst[5 - i] = ovl * TWID3[5 - i] + sum * TWID3[2 - i];
    }
}

fn l3_imdct_short(g: &mut [f32], gbase: usize, overlap: &mut [f32], obase: usize, nbands: usize) {
    for b in 0..nbands {
        let (go, oo) = (gbase + 18 * b, obase + 9 * b);
        let mut tmp = [0.0f32; 18];
        tmp.copy_from_slice(&g[go..go + 18]);
        g[go..go + 6].copy_from_slice(&overlap[oo..oo + 6]);
        let (ov6, ov3) = overlap[oo..oo + 9].split_at_mut(6);
        l3_imdct12(&tmp, &mut g[go + 6..go + 12], ov3);
        l3_imdct12(&tmp[1..], &mut g[go + 12..go + 18], ov3);
        l3_imdct12(&tmp[2..], ov6, ov3);
    }
}

fn l3_change_sign(g: &mut [f32], base: usize) {
    let mut off = base + 18;
    for _ in (0..32).step_by(2) {
        for i in (1..18).step_by(2) {
            g[off + i] = -g[off + i];
        }
        off += 36;
    }
}

fn l3_imdct_gr(g: &mut [f32], base: usize, overlap: &mut [f32], block_type: u8, n_long_bands: usize) {
    let (mut gb, mut ob) = (base, 0);
    if n_long_bands != 0 {
        l3_imdct36(g, gb, overlap, ob, &MDCT_WINDOW[0], n_long_bands);
        gb += 18 * n_long_bands;
        ob += 9 * n_long_bands;
    }
    if block_type == SHORT_BLOCK_TYPE {
        l3_imdct_short(g, gb, overlap, ob, 32 - n_long_bands);
    } else {
        l3_imdct36(g, gb, overlap, ob, &MDCT_WINDOW[usize::from(block_type == STOP_BLOCK_TYPE)], 32 - n_long_bands);
    }
}

